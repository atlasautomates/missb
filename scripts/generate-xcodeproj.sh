#!/usr/bin/env bash
# Regenerates MissB.xcodeproj from project.yml.
# Reads APPLE_TEAM_ID from .env when present. Never writes or deletes .env.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

if ! command -v xcodegen >/dev/null 2>&1; then
  echo "xcodegen not found. Install with: brew install xcodegen" >&2
  exit 1
fi

team=""
if [[ -f .env ]]; then
  raw="$(grep -E '^[[:space:]]*APPLE_TEAM_ID=' .env | tail -n 1 | cut -d= -f2- || true)"
  raw="${raw//\"/}"
  raw="${raw//\'/}"
  raw="${raw//[[:space:]]/}"
  if [[ -n "$raw" ]]; then
    if [[ "$raw" =~ ^[A-Za-z0-9]{10}$ ]]; then
      team="$raw"
    else
      echo "warning: APPLE_TEAM_ID is set but is not a 10-character team id; leaving the team unset" >&2
    fi
  fi
fi

mkdir -p Config
{
  echo "// Generated by scripts/generate-xcodeproj.sh. Gitignored — may contain a team id."
  echo "CODE_SIGN_STYLE = Automatic"
  if [[ -n "$team" ]]; then
    echo "DEVELOPMENT_TEAM = ${team}"
  else
    # No team yet. Ad-hoc / unsigned simulator builds still install and launch.
    echo "CODE_SIGN_IDENTITY[sdk=watchsimulator*] = -"
    echo "CODE_SIGNING_REQUIRED[sdk=watchsimulator*] = NO"
    echo "CODE_SIGNING_ALLOWED[sdk=watchsimulator*] = NO"
  fi
} > Config/Signing.xcconfig

# Listener URL and bearer token stay out of git. Empty values still build;
# Send on the watch then reports that it is not set up.
listener_url=""
listener_token=""
if [[ -f .env ]]; then
  listener_url="$(grep -E '^[[:space:]]*LISTENER_URL=' .env | tail -n 1 | cut -d= -f2- || true)"
  listener_token="$(grep -E '^[[:space:]]*LISTENER_TOKEN=' .env | tail -n 1 | cut -d= -f2- || true)"
  listener_url="${listener_url//\"/}"
  listener_url="${listener_url//\'/}"
  listener_token="${listener_token//\"/}"
  listener_token="${listener_token//\'/}"
fi
# Hex tokens and https URLs need no further escaping inside a Swift string.
if [[ -n "$listener_url" ]]; then
  if [[ "$listener_url" != https://* ]] || [[ "$listener_url" == *[[:space:]]* ]] || [[ "$listener_url" == *\"* ]]; then
    echo "warning: LISTENER_URL is not a plain https URL; Send will be unset" >&2
    listener_url=""
  fi
fi
if [[ -n "$listener_token" && ! "$listener_token" =~ ^[A-Fa-f0-9]+$ ]]; then
  echo "warning: LISTENER_TOKEN is not hex; Send will be unset" >&2
  listener_token=""
fi
cat > WatchApp/ListenerConfig.swift <<EOF
// Generated by scripts/generate-xcodeproj.sh from .env. Gitignored.
import Foundation

enum ListenerConfig {
    static let url = "${listener_url}"
    static let token = "${listener_token}"
}
EOF

xcodegen generate --spec project.yml
echo "generated MissB.xcodeproj (team $([[ -n "$team" ]] && echo set || echo unset), listener $([[ -n "$listener_token" && -n "$listener_url" ]] && echo set || echo unset))"
